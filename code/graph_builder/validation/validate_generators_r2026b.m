function report = validate_generators_r2026b()
%VALIDATE_GENERATORS_R2026B Run one static and runtime check for graph generators.
% Covers all 16 model families and all 20 supported direction-specific APIs.
% The JVM is required to save 16 graph-v1 validation samples and test I/O.

root = fileparts(fileparts(mfilename('fullpath')));
validation_dir = fullfile(root, 'validation');
addpath(root);
setup_generators();
addpath(validation_dir);

log_path = fullfile(validation_dir, 'r2026b_generator_validation.log');
report_path = fullfile(validation_dir, 'r2026b_generator_report.json');
log_file = fopen(log_path, 'wt');
if log_file < 0
    error('graphgen:ValidationLogOpen', 'Cannot open validation log: %s', log_path);
end
log_cleanup = onCleanup(@() fclose(log_file)); %#ok<NASGU>

write_log(log_file, 'R2026b generator validation started.');
write_log(log_file, 'MATLAB version: %s', version);
write_log(log_file, 'JVM available: %d', usejava('jvm'));
write_log(log_file, 'Root: %s', root);
assert(usejava('jvm'), 'R2026b complete validation requires an active JVM.');
write_log(log_file, 'Java: %s', version('-java'));
implementation = gg_implementation_digest();

static = check_project_sources(root, log_file);
assert(static.failed_files == 0 && static.error_count == 0, ...
    'Static analysis has %d execution failures and %d error diagnostics. See %s.', ...
    static.failed_files, static.error_count, log_path);

write_log(log_file, 'Running fixed-sample repeatability and invariant checks.');
fixed_samples = test_16_models_r2026b(fullfile(validation_dir, 'r2026b_samples'));

write_log(log_file, 'Running source-defined boundaries and all standard API checks.');
standard = test_standard_models();

write_log(log_file, 'Comparing EH/RT/RR/RH outputs against author reference sources.');
author_results = test_author_models();
author_matched = sum(strcmp({author_results.status}, 'matched'));
author_verified_failures = numel(author_results) - author_matched;
author_saturation = test_author_saturation();
batch = test_batch_all_models();

if usejava('jvm')
    write_log(log_file, 'Running graph-v1 I/O checks (JVM available).');
    test_graph_io();
    graph_io_test = 'passed';
    write_log(log_file, 'Graph-v1 I/O checks passed.');
else
    graph_io_test = 'not_run_jvm_unavailable';
    write_log(log_file, 'Graph-v1 I/O checks skipped (JVM unavailable).');
end

report = struct( ...
    'matlab_version', version, ...
    'implementation_version', fixed_samples.implementation_version, ...
    'implementation_sha256', implementation, ...
    'author_saturation', author_saturation, 'batch_all_models', batch, ...
    'jvm_available', usejava('jvm'), 'java_version', version('-java'), ...
    'model_family_count', 16, ...
    'supported_generator_interface_count', 20, ...
    'static_analysis', static, ...
    'fixed_sample_repeatability', struct( ...
        'case_count', fixed_samples.case_count, ...
        'passed', fixed_samples.passed, ...
        'failed', fixed_samples.failed, ...
        'saved_sample_count', fixed_samples.manifest_count, ...
        'sample_output_root', fixed_samples.sample_output_root), ...
    'standard_model_checks', standard, ...
    'author_source_comparison', struct( ...
        'case_count', numel(author_results), ...
        'matched', author_matched, ...
        'verified_source_failures', author_verified_failures), ...
    'jvm_dependent_graph_io_test', graph_io_test, ...
    'completed_utc', char(datetime('now', 'TimeZone', 'UTC', ...
        'Format', "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'")));

assert(strcmp(implementation, gg_implementation_digest()), ...
    'Generator implementation changed during validation.');
write_report(report_path, jsonencode(report, 'PrettyPrint', true));
write_log(log_file, 'Summary: %d files; %d checkcode diagnostics; %d analyzer failures; %d severity=error diagnostics.', ...
    static.file_count, static.diagnostic_count, static.failed_files, static.error_count);
write_log(log_file, 'Repeatability: %d/%d fixed model samples passed.', ...
    fixed_samples.passed, fixed_samples.case_count);
write_log(log_file, 'Standard supported interfaces: %d; unsupported direction checks: %d.', ...
    standard.supported_interfaces, standard.unsupported_interfaces);
write_log(log_file, 'Author source comparison: %d matched; %d verified source failures.', ...
    author_matched, author_verified_failures);
write_log(log_file, 'JVM-dependent graph I/O test: %s.', graph_io_test);
write_log(log_file, 'Report: %s', report_path);

fprintf(['R2026B_GENERATOR_VALIDATION_OK: %d model families, %d supported APIs, ', ...
    '%d source files parsed. Report: %s\n'], ...
    report.model_family_count, report.supported_generator_interface_count, ...
    static.file_count, report_path);
end

function result = check_project_sources(root, log_file)
source_dirs = {'common', 'directed', 'undirected', 'io', 'batch', 'validation'};
files = dir(fullfile(root, '*.m'));
for directory_index = 1:numel(source_dirs)
    folder = fullfile(root, source_dirs{directory_index});
    files = [files; dir(fullfile(folder, '**', '*.m'))]; %#ok<AGROW>
end

paths = unique(fullfile({files.folder}, {files.name}), 'stable');
diagnostics = repmat(struct( ...
    'file', '', 'id', '', 'line', 0, 'message', ''), 0, 1);
failed_files = repmat(struct('file', '', 'message', ''), 0, 1);

for file_index = 1:numel(paths)
    relative_path = erase(paths{file_index}, [root, filesep]);
    try
        messages = checkcode(paths{file_index}, '-id', '-config=factory');
        for message_index = 1:numel(messages)
            item = struct( ...
                'file', strrep(relative_path, filesep, '/'), ...
                'id', messages(message_index).id, ...
                'line', messages(message_index).line, ...
                'message', messages(message_index).message);
            diagnostics(end+1, 1) = item; %#ok<AGROW>
            write_log(log_file, 'CHECKCODE %s:%d %s %s', item.file, item.line, ...
                item.id, item.message);
        end
    catch exception
        failed = struct( ...
            'file', strrep(relative_path, filesep, '/'), ...
            'message', exception.message);
        failed_files(end+1, 1) = failed; %#ok<AGROW>
        write_log(log_file, 'CHECKCODE_FAIL %s: %s', failed.file, failed.message);
    end
end

% checkcode returns syntax problems as diagnostics, not necessarily exceptions.
% Use the documented severity API to count errors independently of exceptions.
analysis = codeIssues(string(paths), IncludeSubfolders=false, CodeAnalyzerConfiguration="factory");
issues = analysis.Issues;
error_mask = issues.Severity == "error";
error_rows = issues(error_mask, :);
errors = repmat(struct('file', '', 'id', '', 'line', 0, 'message', ''), height(error_rows), 1);
for k = 1:height(error_rows)
    errors(k) = struct( ...
        'file', strrep(erase(char(error_rows.FullFilename(k)), [root filesep]), filesep, '/'), ...
        'id', char(string(error_rows.CheckID(k))), 'line', error_rows.LineStart(k), ...
        'message', char(error_rows.Description(k)));
    write_log(log_file, 'CODE_ERROR %s:%d %s %s', ...
        errors(k).file, errors(k).line, errors(k).id, errors(k).message);
end

result = struct( ...
    'file_count', numel(paths), ...
    'severity_file_count', numel(analysis.Files), ...
    'error_count', height(error_rows), 'errors', errors, ...
    'warning_count', sum(issues.Severity == "warning"), ...
    'info_count', sum(issues.Severity == "info"), ...
    'diagnostic_count', numel(diagnostics), ...
    'failed_files', numel(failed_files), ...
    'diagnostics', diagnostics, ...
    'failures', failed_files);
end

function write_log(file_id, format_string, varargin)
fprintf(file_id, '[%s] ', char(datetime('now', 'TimeZone', 'UTC', ...
    'Format', "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'")));
fprintf(file_id, [format_string, '\n'], varargin{:});
end

function write_report(path, text)
file = fopen(path, 'wt');
if file < 0
    error('graphgen:ValidationReportOpen', 'Cannot open validation report: %s', path);
end
cleanup = onCleanup(@() fclose(file)); %#ok<NASGU>
fprintf(file, '%s\n', text);
end
