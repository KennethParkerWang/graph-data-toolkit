function classification = gg_batch_source(model, direction)
%GG_BATCH_SOURCE Classify only protocols actually supported by this release.
if ismember(model,{'eh','rt','rr','rh'})
    classification = 'author_matlab_port_with_explicit_source_failure_guards';
elseif strcmp(model,'sf')
    classification = 'original_static_weighted_rejection';
elseif strcmp(model,'qs')
    classification = 'original_q_snapback_single_layer';
else
    labels = struct('er','independent_bernoulli_pairs', ...
        'er_gnm','uniform_fixed_edge_count','ba','networkx_star_seed_preferential_attachment', ...
        'ws','networkx_ring_rewiring','nw','networkx_edge_order_shortcuts', ...
        'sbm','independent_block_probabilities','rgg','open_unit_cube_geometry', ...
        'random_regular','networkx_pairing_restart','hk','networkx_powerlaw_cluster', ...
        'chung_lu','networkx_clipped_product_probabilities_without_selfloops', ...
        'lfr','networkx_discrete_lfr_explicit_wiring_no_selfloops_with_budget', ...
        'degree_sequence','havel_hakimi_then_finite_degree_preserving_swaps', ...
        'dc_sbm','poisson_block_model_simple_projection_without_loops', ...
        'waxman','waxman1_actual_euclidean_distances', ...
        'duplication_divergence','networkx_connected_duplication_with_attempt_budget', ...
        'rhg','hyperbolic_radial_distribution_fermi_connection', ...
        'forest_fire','snap_zero_based_geometric_new_to_old_dag');
    if ~isfield(labels,model), error('graphgen:BatchModel','Unsupported model: %s.',model); end
    classification = labels.(model);
end
classification = [direction ':' classification];
end
